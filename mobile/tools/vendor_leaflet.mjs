// Regenerate src/ui/map/leafletDist.ts from node_modules/leaflet/dist.
//
// The map runs in a WebView, and it used to load Leaflet from unpkg — a hard
// CDN dependency in an app whose whole premise is working in a park. The
// library is vendored as a checked-in string module instead, so the map shell
// opens with no network at all (the tiles still need one; the library must
// not). Run this after upgrading the leaflet devDependency:
//
//   node tools/vendor_leaflet.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const dist = dirname(require.resolve("leaflet/package.json")) + "/dist";
const version = require("leaflet/package.json").version;

// A literal "</script>" inside the payload would end the inline <script> tag
// early. In valid JS any such occurrence sits inside a string, where the
// escaped slash is a no-op.
const js = readFileSync(join(dist, "leaflet.js"), "utf8")
  .replace(/<\/script/gi, "<\\/script");
const css = readFileSync(join(dist, "leaflet.css"), "utf8");

const out = `// GENERATED by tools/vendor_leaflet.mjs — do not edit.
// Leaflet ${version}, inlined so the map opens offline. See that script for why.
/* eslint-disable */
export const LEAFLET_VERSION = ${JSON.stringify(version)};
export const LEAFLET_JS: string = ${JSON.stringify(js)};
export const LEAFLET_CSS: string = ${JSON.stringify(css)};
`;

const target = join(dirname(fileURLToPath(import.meta.url)),
                    "..", "src", "ui", "map", "leafletDist.ts");
writeFileSync(target, out);
console.log(`vendored leaflet ${version} → ${target}`);
