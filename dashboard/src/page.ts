import { useEffect, useState } from "react";

/**
 * Which page the dashboard is on, kept in the URL hash.
 *
 * The hash rather than component state so a reload, a bookmark and the browser's
 * back button all land where they should. The operator dashboard is a thing
 * people leave open on a second monitor for hours; a refresh that silently threw
 * away which page they were on would be noticed every time.
 *
 * Hash rather than a router: a handful of pages do not justify a dependency, and
 * the server serves this as a single static bundle with no path routing behind
 * it — a real path would 404 on reload.
 */
export const PAGES = {
  overview: "Overview",
  captures: "Captures",
  // Its own page rather than a panel on the overview. The log is the thing you
  // open when something is already wrong, and it was sitting between the
  // semantics matrix and the fleet panels — where it pushed them down the page
  // every day for the sake of the days it is needed.
  logs: "Logs",
  // Its own page for the same reason as the log: it matters intensely for a few
  // hours and not at all the rest of the week, and a progress bar that is empty
  // six days in seven does not earn a slot on the overview. Named for what it
  // became: training runs, corpus scans and crawls all report here now.
  progress: "Progress Monitor",
  // The training corpus — what the collection tooling gathered and what the
  // detector heard in it. A different thing from Captures, which is the field
  // recordings this server owns.
  corpus: "Corpus",
  // Ask CrowGPT for a call, get the clip back as a reply. Synthetic audio,
  // generated by the worker in crowgpt's venv — nothing here touches the corpus.
  chat: "Crow Chat",
} as const;

export type Page = keyof typeof PAGES;

function fromHash(): Page {
  const name = window.location.hash.replace(/^#\/?/, "");
  return name in PAGES ? (name as Page) : "overview";
}

export function usePage(): [Page, (page: Page) => void] {
  const [page, setPage] = useState<Page>(fromHash);

  useEffect(() => {
    // Covers the back button and anyone editing the hash by hand.
    const sync = () => setPage(fromHash());
    window.addEventListener("hashchange", sync);
    return () => window.removeEventListener("hashchange", sync);
  }, []);

  return [
    page,
    (next: Page) => {
      // Writing the hash fires hashchange, which sets the state. Setting it here
      // too would render once from state and once from the event.
      window.location.hash = next === "overview" ? "/" : `/${next}`;
    },
  ];
}
