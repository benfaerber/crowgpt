#!/usr/bin/env bash
# Mint the field server's two secrets once, and print them as shell exports.
#
# The server refuses to bind the network with its built-in dev tokens, which
# would otherwise make `make field` a two-step ceremony every time. Generating
# them here keeps it one command — and generating them *once*, into a file,
# matters more than it looks: the enrollment token is typed into the phone's
# Settings by hand, so a token that changed per run would mean re-enrolling
# before every session, and every capture already on the phone would come back
# as "not your capture".
#
#   eval "$(tools/secrets.sh)"     # exports FIELD_ENROLL_TOKEN + FIELD_OPERATOR_TOKEN
#   tools/secrets.sh --show        # print them for typing into the app

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SECRETS="$HERE/../instance/secrets.env"

if [ ! -f "$SECRETS" ]; then
  mkdir -p "$(dirname "$SECRETS")"
  # 0600 before anything is written — the file is only ever as private as it
  # was at creation.
  touch "$SECRETS"
  chmod 600 "$SECRETS"
  {
    echo "# Generated by tools/secrets.sh. Under instance/, so gitignored."
    echo "export FIELD_ENROLL_TOKEN=$(python3 -c 'import secrets; print(secrets.token_urlsafe(24))')"
    echo "export FIELD_OPERATOR_TOKEN=$(python3 -c 'import secrets; print(secrets.token_urlsafe(24))')"
  } >>"$SECRETS"
fi

if [ "${1:-}" = "--show" ]; then
  # shellcheck source=/dev/null
  . "$SECRETS"
  echo "  enrollment token — type into the app's Settings:  $FIELD_ENROLL_TOKEN"
  echo "  operator token   — sign in to the dashboard at /:  $FIELD_OPERATOR_TOKEN"
  echo "  both stored in:  fieldserver/instance/secrets.env"
else
  cat "$SECRETS"
fi
